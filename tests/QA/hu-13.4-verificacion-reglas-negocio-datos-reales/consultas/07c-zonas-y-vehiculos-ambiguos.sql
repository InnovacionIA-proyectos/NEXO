-- B) Qué TIPOVEHICULO aparece REALMENTE en tarifas de plaza para las 5
-- líneas cuyo vehículo no tiene código exacto en el catálogo (2, 8, 9, 10, 15)
-- — sin filtrar por vehículo, dejamos que el dato real nos diga cuál usan.
-- Reemplazar <<ZONA_...>> una vez tengamos el resultado de A).
