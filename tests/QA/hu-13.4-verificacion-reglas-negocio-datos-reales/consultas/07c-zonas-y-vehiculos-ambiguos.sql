-- ============================================================
-- A) Zonas de las 14 ciudades del pliego (sin TOP, texto directo).
-- ============================================================
SELECT ID, IDZONATARIFICACION, IDZONATRANSPORTE
FROM dbo.tblZonasTarificacionRelacion
WHERE IDZONATRANSPORTE LIKE '%BUENAVENTURA%' OR IDZONATARIFICACION LIKE '%BUENAVENTURA%'
   OR IDZONATRANSPORTE LIKE '%BOGOTA%'      OR IDZONATARIFICACION LIKE '%BOGOTA%'
   OR IDZONATRANSPORTE LIKE '%MEDELLIN%'    OR IDZONATARIFICACION LIKE '%MEDELLIN%'
   OR IDZONATRANSPORTE LIKE '%VABURRA%'     OR IDZONATARIFICACION LIKE '%VABURRA%'
   OR IDZONATRANSPORTE LIKE '%CALI%'        OR IDZONATARIFICACION LIKE '%CALI%'
   OR IDZONATRANSPORTE LIKE '%CARTAGENA%'   OR IDZONATARIFICACION LIKE '%CARTAGENA%'
   OR IDZONATRANSPORTE LIKE '%BUCARAMANGA%' OR IDZONATARIFICACION LIKE '%BUCARAMANGA%'
   OR IDZONATRANSPORTE LIKE '%BARRANQUILLA%' OR IDZONATARIFICACION LIKE '%BARRANQUILLA%'
   OR IDZONATRANSPORTE LIKE '%CUCUTA%'      OR IDZONATARIFICACION LIKE '%CUCUTA%'
   OR IDZONATRANSPORTE LIKE '%VILLAVICENCIO%' OR IDZONATARIFICACION LIKE '%VILLAVICENCIO%'
   OR IDZONATRANSPORTE LIKE '%PEREIRA%'     OR IDZONATARIFICACION LIKE '%PEREIRA%'
   OR IDZONATRANSPORTE LIKE '%MANIZALES%'   OR IDZONATARIFICACION LIKE '%MANIZALES%'
   OR IDZONATRANSPORTE LIKE '%SANTA MARTA%' OR IDZONATARIFICACION LIKE '%SANTA MARTA%'
   OR IDZONATRANSPORTE LIKE '%IBAGUE%'      OR IDZONATARIFICACION LIKE '%IBAGUE%'
   OR IDZONATRANSPORTE LIKE '%NEIVA%'       OR IDZONATARIFICACION LIKE '%NEIVA%'
ORDER BY IDZONATARIFICACION, IDZONATRANSPORTE;

